for i, (fname, title, subtitle) in enumerate(PUBS):
    obj, created = Publication.objects.update_or_create(
        title=title,
        defaults=dict(subtitle=subtitle, order=i, is_visible=True),
    )
    path = os.path.join(COVERS, fname)
    if COVERS and os.path.exists(path) and not obj.cover:
        with open(path, 'rb') as f:
            obj.cover.save(fname, File(f), save=True)
print('publications:', Publication.objects.count())

