for slug, items in QA.items():
    disease = Disease.objects.filter(slug=slug).first()
    if not disease:
        print('нет заболевания', slug)
        continue
    for question, answer in items:
        Faq.objects.create(order=order, question=question, answer=answer, disease=disease, is_visible=True)
        order += 1
